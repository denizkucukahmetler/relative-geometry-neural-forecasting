import torch
from torch.utils.data import Dataset

class DynamicalDataset(Dataset):
    '''
    A Dataset class for dynamical data.
    Extends torch.utils.data.Dataset.

    Items can be accessed using __getitem__(idx) (not preferred, but useful when we want to get the same samples from multiple datasets).
    Or using a torch.utils.data.DataLoader (preferred). The Dataloader can iterate over the items and will take care of sampling and batching.
    The dataset will always contain as many samples as possible. Later on, we can split the dataset into train, test and val and sample from it.
    '''
    def __init__(self, enc_inputs, dec_inputs, dec_targets, timesteps, scalers):
        '''
        Constructor.
        
        Args:
            enc_inputs: torch.Tensor (num_samples, enc_input_length, sample_dims). Encoder inputs as generated by the DataHandler
            dec_inputs: torch.Tensor (num_samples, dec_input_length, sample_dims). Decoder Inputs (mainly for teacher forcing during RNN training)
                dec_inputs is like dec_targets, but starts and ends one point earlier.
            dec_targets: torch.Tensor (num_samples, dec_target_length, sample_dims). Decoder Targets
            scalers: np.array[TensorNormalizer] of length num_samples. One Scaler for each sample. Since the samples are already normalized, we will use these
                to denormalize later
            timesteps: torch.Tensor (num_samples, dec_target_length). Timesteps of the targets for the NODE. Always start at 0.0.
        '''
        self.enc_inputs = enc_inputs    
        self.dec_inputs = dec_inputs
        self.dec_targets = dec_targets  
        self.scalers = scalers           
        self.timesteps = timesteps    
    
    def __len__(self):
        '''
        Will return the number of samples in the dataset.
        '''
        return self.enc_inputs.shape[0]  
    
    def __getitem__(self, index):
        '''
        Will retrieve the sample with the specified index.

        Args:
            index (int): The index of the sample to be retrieved.
        
        Returns:
            enc_input: torch.Tensor of shape (enc_input_length, dimensionality_of_data)
            dec_input: torch.Tensor of shape (dec_input_length, dimensionality_of_data)
            dec_target: torch.Tensor of shape (dec_target_length, dimensionality_of_data)
            scaler: TensorNormalizer
            timestep: torch.Tensor of shape (dec_target_length)
        '''
        # Get the data for the specified index
        enc_input = self.enc_inputs[index]    
        dec_input = self.dec_inputs[index]     
        dec_target = self.dec_targets[index]   
        scaler = self.scalers[index]                
        timestep = self.timesteps[index]     
        
        # Return a tuple of the retrieved data
        return enc_input, dec_input, dec_target, timestep, scaler
